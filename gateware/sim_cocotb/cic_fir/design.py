"""Design the decimate-by-5 FIR for the cicfir receiver chain and write its coefficients.

Chain (76.8 MHz ADC clock):
  mixer -> cic_s1 (N=4, R=16, 4.8 MHz) -> second CIC (N=4, R=5, 960 kHz) -> FIR /5 -> 192 kHz

The FIR passes |f| <= FP and rejects the bands that fold onto the passband when the
960 kHz stream is decimated by 5 (192k +- FP and 384k +- FP). What folds into FP..96 kHz is
left alone, so the clean band is +-FP.

  .venv/bin/python design.py            # print the response, write the coefficient include
  .venv/bin/python design.py --check    # print only

Writes ../../rtl/radio_openhpsdr1/cic_fir_coefs.vh and coefs.txt (one integer per line,
read by the cocotb model).
"""
import argparse, os
import numpy as np
import scipy.signal as ss

FS_ADC = 76.8e6
FS_IN = 960e3          # FIR input rate (second CIC output)
DEC = 5
FP = 75e3              # passband edge
NTAPS = 109            # odd, symmetric
CBITS = 18             # signed coefficient width (one 18x18 multiplier per MAC unit)
# Gain. The old chain (cic_s2 R=25 into 24 bits) gives out = x_s1 * 64 * 25^4 / 2^19.
# The new second CIC gives x_s1 * 5^4 / 2^10 at 18 bits, so the FIR must add the rest.
OLD_GAIN = 64 * 25**4 / 2**19
CIC2_GAIN = 5**4 / 2**10
FIR_GAIN = OLD_GAIN / CIC2_GAIN          # 78.125: keeps the cicrx output level

HERE = os.path.dirname(os.path.abspath(__file__))
VH = os.path.join(HERE, '..', '..', 'rtl', 'radio_openhpsdr1', 'cic_fir_coefs.vh')
TXT = os.path.join(HERE, 'coefs.txt')


def cic(f, R, N, fs):
    x = np.pi * np.asarray(f, float) / fs
    with np.errstate(all='ignore'):
        h = np.where(np.abs(np.sin(x)) < 1e-15, 1.0, np.sin(R * x) / (R * np.sin(x)))
    return np.abs(h) ** N


def cic_chain(f):
    return cic(f, 16, 4, FS_ADC) * cic(f, 5, 4, FS_ADC / 16)


def design():
    bands = [0, FP, 192e3 - FP, 192e3 + FP, 384e3 - FP, FS_IN / 2]
    h = ss.remez(NTAPS, bands, [1, 0, 0], weight=[1, 30, 30], fs=FS_IN, maxiter=200)
    h = h / h.sum()
    # Largest shift that keeps every coefficient inside CBITS signed.
    peak = np.max(np.abs(h)) * FIR_GAIN
    sh = int(np.floor(np.log2((2 ** (CBITS - 1) - 1) / peak)))
    hq = np.round(h * FIR_GAIN * 2 ** sh).astype(np.int64)
    assert np.all(hq == hq[::-1]), 'coefficients must stay symmetric'
    assert np.max(np.abs(hq)) < 2 ** (CBITS - 1)
    return hq, sh


def response(hq, sh):
    """Per-frequency gain at the output, and the worst image folding onto each output frequency."""
    f = np.linspace(0, 96e3, 961)
    w = 2 * np.pi * f / FS_IN

    def fir(fr):
        n = np.arange(len(hq))
        return np.abs(np.exp(-1j * np.outer(2 * np.pi * fr / FS_IN, n)) @ hq) / 2 ** sh / FIR_GAIN

    g = cic_chain(f) * fir(f)
    worst = np.zeros_like(f)
    for k in range(1, int(FS_ADC / 2 / 192e3) + 2):
        for s in (1, -1):
            fa = np.abs(s * k * 192e3 + f)
            worst = np.maximum(worst, cic_chain(fa) * fir(fa))
    return f, g, worst


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    hq, sh = design()
    print(f'{NTAPS} taps, {CBITS}-bit coefficients, output shift {sh}, '
          f'peak {np.max(np.abs(hq))}, sum {hq.sum()} (target {FIR_GAIN * 2**sh:.1f})')
    f, g, worst = response(hq, sh)
    pb = f <= FP
    print(f'passband 0..{FP/1e3:.0f} kHz: gain {20*np.log10(g[pb].min()):+.3f} .. '
          f'{20*np.log10(g[pb].max()):+.3f} dB (CIC droop included)')
    print(f'worst image in passband: {20*np.log10(np.max(worst[pb] / g[pb])):.1f} dBc')
    print('  kHz   gain dB   worst image dBc')
    for fk in (0, 20, 40, 60, 70, 75, 80, 85, 90):
        i = int(round(fk * 10))
        print(f'  {fk:3d}  {20*np.log10(g[i]):+8.3f}  {20*np.log10(worst[i] / g[i]):9.1f}')
    if args.check:
        return
    with open(TXT, 'w') as fp:
        fp.write(f'# shift {sh}\n')
        fp.writelines(f'{int(c)}\n' for c in hq)
    with open(VH, 'w') as fp:
        fp.write('// Generated by gateware/sim_cocotb/cic_fir/design.py. Do not edit.\n')
        fp.write(f'// {NTAPS}-tap decimate-by-5 FIR, 960 -> 192 ksps, passband +-{FP/1e3:.0f} kHz.\n')
        fp.write(f'localparam FIR_NTAPS = {NTAPS};\n')
        fp.write(f'localparam FIR_SHIFT = {sh};\n')
        fp.write('function automatic signed [17:0] fir_coef(input [6:0] k);\n')
        fp.write('  case (k)\n')
        for k, c in enumerate(hq):
            fp.write(f"    7'd{k}: fir_coef = {'-' if c < 0 else ''}18'sd{abs(int(c))};\n")
        fp.write("    default: fir_coef = 18'sd0;\n  endcase\nendfunction\n")
    print('wrote', os.path.relpath(VH), 'and', os.path.relpath(TXT))


if __name__ == '__main__':
    main()
